import crypto from 'crypto';
import fs from 'fs/promises';
import path from 'path';
import { HttpError } from '../auth/auth.types';

/**
 * KYC documents hold identity data, so they are never served as public static files.
 * Files are written under KYC_STORAGE_DIR with a random name and streamed back only through the
 * admin-only endpoint GET /admin/partners/:id/kyc/documents/:docId.
 *
 * Swap saveKycDocument / readKycDocument for S3 later; callers only use storageKey.
 */
export const MAX_KYC_FILE_BYTES = 5 * 1024 * 1024;

const ALLOWED: Record<string, { ext: string; magic: number[] }> = {
  'application/pdf': { ext: 'pdf', magic: [0x25, 0x50, 0x44, 0x46] }, // %PDF
  'image/png': { ext: 'png', magic: [0x89, 0x50, 0x4e, 0x47] },
  'image/jpeg': { ext: 'jpg', magic: [0xff, 0xd8, 0xff] },
};

const storageDir = () => process.env.KYC_STORAGE_DIR || path.resolve(process.cwd(), 'storage', 'kyc');

const invalid = (message: string) => new HttpError(400, message, 'INVALID_KYC_DOCUMENT');

export interface StoredKycFile {
  storageKey: string;
  mimeType: string;
  size: number;
}

/** Accepts a `data:<mime>;base64,<payload>` string from the register form. */
export async function saveKycDocument(dataUrl: string, label: string): Promise<StoredKycFile> {
  const match = /^data:([a-z]+\/[a-z0-9.+-]+);base64,([A-Za-z0-9+/=\r\n]+)$/i.exec(dataUrl ?? '');
  if (!match) throw invalid(`${label}: upload a PDF, JPG or PNG file.`);

  const mimeType = match[1].toLowerCase();
  const rule = ALLOWED[mimeType];
  if (!rule) throw invalid(`${label}: only PDF, JPG and PNG files are accepted.`);

  const buffer = Buffer.from(match[2], 'base64');
  if (buffer.length === 0) throw invalid(`${label}: the file is empty.`);
  if (buffer.length > MAX_KYC_FILE_BYTES) throw invalid(`${label}: file must be under 5MB.`);
  // Trust the bytes, not the declared type.
  if (!rule.magic.every((byte, i) => buffer[i] === byte)) {
    throw invalid(`${label}: the file content does not match its type.`);
  }

  const storageKey = `${crypto.randomUUID()}.${rule.ext}`;
  await fs.mkdir(storageDir(), { recursive: true });
  await fs.writeFile(path.join(storageDir(), storageKey), buffer, { mode: 0o600 });
  return { storageKey, mimeType, size: buffer.length };
}

export async function readKycDocument(storageKey: string): Promise<Buffer> {
  // storageKey is generated by us, but never let a bad DB value escape the directory.
  if (path.basename(storageKey) !== storageKey) throw new HttpError(404, 'Document not found', 'NOT_FOUND');
  const fullPath = path.join(storageDir(), storageKey);
  try {
    return await fs.readFile(fullPath);
  } catch (err) {
    // Tells you where the server looked: if this path is not where the register upload wrote the file,
    // set KYC_STORAGE_DIR to one fixed folder in .env.
    console.error('[kyc-storage] cannot read', fullPath, (err as NodeJS.ErrnoException).code);
    throw new HttpError(404, `Document file is missing on the server (${storageKey})`, 'NOT_FOUND');
  }
}
