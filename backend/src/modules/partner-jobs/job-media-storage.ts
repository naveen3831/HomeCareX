import crypto from "crypto";
import fs from "fs/promises";
import path from "path";
import { HttpError } from "../auth/auth.types";

/**
 * Photos and videos the partner adds when starting a job (proof of the place before work begins).
 * They are written under JOB_MEDIA_STORAGE_DIR with a random name and are only served through the
 * admin-only endpoint GET /admin/bookings/:bookingId/start-media/:key, never as public files.
 *
 * Swap saveJobMedia / readJobMedia for S3 later; callers only use the storage key.
 */
export const MAX_START_MEDIA = 5;
export const MAX_START_IMAGE_BYTES = 5 * 1024 * 1024;
export const MAX_START_VIDEO_BYTES = 50 * 1024 * 1024;

type Kind = "image" | "video";

const startsWith = (buf: Buffer, bytes: number[], offset = 0) =>
  bytes.every((b, i) => buf[offset + i] === b);

// "ftyp" at byte 4 marks an MP4 / QuickTime (MOV) file.
const isIsoVideo = (buf: Buffer) => startsWith(buf, [0x66, 0x74, 0x79, 0x70], 4);

const ALLOWED: Record<string, { ext: string; kind: Kind; ok: (b: Buffer) => boolean }> = {
  "image/jpeg": { ext: "jpg", kind: "image", ok: (b) => startsWith(b, [0xff, 0xd8, 0xff]) },
  "image/png": { ext: "png", kind: "image", ok: (b) => startsWith(b, [0x89, 0x50, 0x4e, 0x47]) },
  "video/mp4": { ext: "mp4", kind: "video", ok: isIsoVideo },
  "video/quicktime": { ext: "mov", kind: "video", ok: isIsoVideo },
  "video/webm": { ext: "webm", kind: "video", ok: (b) => startsWith(b, [0x1a, 0x45, 0xdf, 0xa3]) },
};

const DEFAULT_DIR = path.resolve(__dirname, "../../../storage/job-media");
const storageDir = () => process.env.JOB_MEDIA_STORAGE_DIR || DEFAULT_DIR;

const invalid = (message: string) => new HttpError(400, message, "INVALID_JOB_MEDIA");

export interface IncomingMedia {
  buffer: Buffer;
  mimetype: string;
}

export interface StoredJobMedia {
  key: string;
  mimeType: string;
  kind: Kind;
  size: number;
  uploadedAt: Date;
}

/** Checks every file first, then writes them. Nothing is kept if any file is rejected. */
export async function saveJobMedia(files: IncomingMedia[]): Promise<StoredJobMedia[]> {
  if (files.length === 0) return [];
  if (files.length > MAX_START_MEDIA) throw invalid(`You can add up to ${MAX_START_MEDIA} photos or videos.`);

  const checked = files.map((file) => {
    const mimeType = (file.mimetype ?? "").toLowerCase();
    const rule = ALLOWED[mimeType];
    if (!rule) throw invalid("Only JPG, PNG, MP4, MOV and WEBM files are accepted.");
    if (file.buffer.length === 0) throw invalid("A file is empty.");
    const limit = rule.kind === "image" ? MAX_START_IMAGE_BYTES : MAX_START_VIDEO_BYTES;
    if (file.buffer.length > limit) {
      throw invalid(rule.kind === "image" ? "A photo must be under 5 MB." : "A video must be under 50 MB.");
    }
    // Trust the bytes, not the declared type.
    if (!rule.ok(file.buffer)) throw invalid("A file's content does not match its type.");
    return { file, mimeType, rule };
  });

  await fs.mkdir(storageDir(), { recursive: true });
  const saved: StoredJobMedia[] = [];
  try {
    for (const { file, mimeType, rule } of checked) {
      const key = `${crypto.randomUUID()}.${rule.ext}`;
      await fs.writeFile(path.join(storageDir(), key), file.buffer, { mode: 0o600 });
      saved.push({ key, mimeType, kind: rule.kind, size: file.buffer.length, uploadedAt: new Date() });
    }
  } catch (err) {
    await deleteJobMedia(saved.map((m) => m.key));
    throw err;
  }
  return saved;
}

export async function readJobMedia(key: string): Promise<Buffer> {
  // The key is generated by us, but never let a bad DB value or URL escape the folder.
  if (path.basename(key) !== key) throw new HttpError(404, "File not found", "NOT_FOUND");
  try {
    return await fs.readFile(path.join(storageDir(), key));
  } catch {
    throw new HttpError(404, "File is missing", "NOT_FOUND");
  }
}

export async function deleteJobMedia(keys: string[]): Promise<void> {
  await Promise.all(
    keys
      .filter((key) => path.basename(key) === key)
      .map((key) => fs.unlink(path.join(storageDir(), key)).catch(() => undefined)),
  );
}
